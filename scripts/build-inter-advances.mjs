// Measured in Chrome, not fontkit: fontkit 2.0.4 cannot apply a weight to a variable woff2 (its
// getVariation rebuilds the font as a plain TTF and loses the cmap).

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import puppeteer from "puppeteer";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const INTER_FILE = join(root, "app", "fonts", "inter-latin-normal.woff2");
const OUT = join(root, "app", "lib", "inter-advances.generated.ts");

// The size .list-filter a renders at (0.875rem). Inter has an optical-size axis, so a glyph measured at
// another size has another width: measured at 1000px, the boxes came out up to 14px short.
const FILTER_PX = 14;

/** @param {Buffer} bytes */
export const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function main() {
  const bytes = readFileSync(INTER_FILE);
  const browser = await puppeteer.launch({ headless: true });
  try {
    const page = await browser.newPage();
    const table = await page.evaluate(async (b64, px) => {
      const buffer = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0)).buffer;
      const face = new FontFace("Measured", buffer, { weight: "100 900" });
      await face.load();
      document.fonts.add(face);
      const ctx = /** @type {CanvasRenderingContext2D} */ (document.createElement("canvas").getContext("2d"));
      ctx.fontKerning = "none";
      /** @type {Record<string, number[]>} */
      const out = {};
      for (const weight of [400, 600]) {
        ctx.font = `${weight} ${px}px Measured`;
        out[weight] = [];
        for (let cp = 32; cp <= 126; cp++) {
          out[weight].push(Math.round((ctx.measureText(String.fromCharCode(cp)).width / px) * 10000) / 10000);
        }
      }
      return out;
    }, bytes.toString("base64"), FILTER_PX);

    const body =
      `// Generated by scripts/build-inter-advances.mjs from app/fonts/inter-latin-normal.woff2. Do not edit.\n` +
      `export const INTER_SHA256 = "${sha256(bytes)}";\n\n` +
      `/** Advance widths in em, unkerned, for code points 32 to 126. */\n` +
      `export const INTER_ADVANCES: Record<400 | 600, readonly number[]> = {\n` +
      `  400: [${table[400].join(", ")}],\n` +
      `  600: [${table[600].join(", ")}],\n` +
      `};\n`;
    writeFileSync(OUT, body);
    console.log(`build:inter-advances ok. ${table[400].length} code points at 400 and 600 into ${OUT}`);
  } finally {
    await browser.close();
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
