// Abscissa's stylesheet for the site's theme, written to app/styles/abscissa.css. A file, not the
// inline <style> Abscissa's README shows, because the public policy allows no inline style element.
// test/cv.test.mjs compares the file with a fresh generation, so an Abscissa upgrade that changes
// the stylesheet fails a test until this is run again.
//
//   npm run build:chart-css

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { dustinedwardsTheme, stylesheet } from "abscissa";

import { isMain } from "./lib/is-main.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CHART_CSS_PATH = path.join(ROOT, "app", "styles", "abscissa.css");

/** The stylesheet as committed: a header naming its source, then Abscissa's own output. */
export function chartCss() {
  const css = stylesheet(dustinedwardsTheme, {
    colorScheme: { dark: '[data-theme="dark"]', light: '[data-theme="light"]' },
  });
  return `/* GENERATED by scripts/build-chart-css.mjs from abscissa's dustinedwardsTheme. Do not edit. */\n${css}\n`;
}

if (isMain(import.meta.url)) {
  await writeFile(CHART_CSS_PATH, chartCss(), "utf8");
  console.log(`build:chart-css wrote ${path.relative(ROOT, CHART_CSS_PATH)}`);
}
