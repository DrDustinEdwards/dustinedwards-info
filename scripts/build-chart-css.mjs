// Enarratio's stylesheet for the site's theme, written to app/styles/enarratio.css. A file, not the
// inline <style> Enarratio's README shows, because the public policy allows no inline style element.
// test/cv.test.mjs compares the file with a fresh generation, so an Enarratio upgrade that changes
// the stylesheet fails a test until this is run again.
//
//   npm run build:chart-css

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { stylesheet } from "enarratio";

import { isMain } from "./lib/is-main.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CHART_CSS_PATH = path.join(ROOT, "app", "styles", "enarratio.css");

// The site's chart theme, which Enarratio published as `dustinedwardsTheme` until 0.2.0: near-white paper,
// the site's sans (Schibsted Grotesk) for chart text, the chart ladder (cadet, purple, claret, sage, gold, rust) for the first six
// series, and the figure ramps for the rest.
/** @type {import("enarratio").Theme} */
const theme = {
  name: "dustinedwards.info",
  fonts: { body: '"Schibsted Grotesk", ui-sans-serif, system-ui, sans-serif' },
  gridlines: "y",
  light: {
    background: "#fdfdfe", text: "#1c1727", mutedText: "#686471", grid: "#dfdce5", focus: "#4f2d7f",
    series: ["#142b42", "#4f2d7f", "#9b3268", "#55684a", "#9a7a0e", "#8a4a1b", "#7d7263", "#6b4a9b"],
    sequential: ["#e3dcf0", "#9279b9", "#6b4a9b", "#4f2d7f", "#3a1f5e"],
    status: { good: "#375445", warning: "#8a4f1e", bad: "#8e1024", unknown: "#a89d8d" },
  },
  dark: {
    background: "#0e0c12", text: "#efedf3", mutedText: "#96949e", grid: "#343238", focus: "#b7a5e0",
    series: ["#5887b5", "#c0b0e6", "#c9699e", "#93b29b", "#efd99c", "#ce7f44", "#ab9f8f", "#a48fd0"],
    sequential: ["#5a4479", "#7f66a8", "#a48fd0", "#c0aee6", "#e0d7f2"],
    status: { good: "#79baa8", warning: "#cf9f5e", bad: "#f0a9b4", unknown: "#6f675c" },
  },
};

/** The stylesheet as committed: a header naming its source, then Enarratio's own output. */
export function chartCss() {
  const css = stylesheet(theme, {
    colorScheme: { dark: '[data-theme="dark"]', light: '[data-theme="light"]' },
  });
  return `/* GENERATED by scripts/build-chart-css.mjs with the site's chart theme. Do not edit. */\n${css}\n`;
}

if (isMain(import.meta.url)) {
  await writeFile(CHART_CSS_PATH, chartCss(), "utf8");
  console.log(`build:chart-css wrote ${path.relative(ROOT, CHART_CSS_PATH)}`);
}
