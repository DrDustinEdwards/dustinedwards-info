// The day each tracked source file last changed, read from git and written to app/lib/source-dates.generated.mjs for
// the sitemap's `lastmod` (app/lib/site-urls.server.ts). A page's date is its own file's last commit, so one commit
// marks changed only the files it touched, never every page at once. The Worker has no git, so this is a build
// product like the published pages (scripts/lib/published-pages.mjs). A content file's source is D1, so where a pull
// wrote it (scripts/pull-sources.mjs) its date is the day D1 last changed it, and the next deploy writes this again.
// build:content and the install step both call it.
//
// A shallow clone (CI's checkout) holds one commit, which would date every file to it: that is no fact about the
// files, so a shallow clone writes no dates and the sitemap leaves `lastmod` out, as it did before.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { readPullManifest } from "./content-source.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SOURCE_DATES_PATH = path.join(ROOT, "app", "lib", "source-dates.generated.mjs");

/** The trees a public page is made from: the content, the data files, and the route modules of the coded pages. */
const SOURCE_TREES = ["content", "data", "app/routes"];

const git = (/** @type {string[]} */ args, cwd = ROOT) => execFileSync("git", args, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

/**
 * Each file's last commit day (`YYYY-MM-DD`, the committer's date in UTC), keyed by its repository path. One `git log`
 * walks history newest first, so the first time a path appears is its latest change. Empty in a shallow clone or
 * where git is missing.
 *
 * @param {string} [cwd]
 * @returns {Record<string, string>}
 */
export function readSourceDates(cwd = ROOT) {
  let log;
  try {
    if (git(["rev-parse", "--is-shallow-repository"], cwd).trim() !== "false") return {};
    log = git(["-c", "log.showSignature=false", "-c", "core.quotePath=false", "log", "--no-renames", "--format=%x00%ct", "--name-only", "--", ...SOURCE_TREES], cwd);
  } catch {
    return {};
  }
  const tracked = new Set(git(["ls-files", "--", ...SOURCE_TREES], cwd).split("\n").filter(Boolean));
  /** @type {Record<string, string>} */
  const dates = {};
  for (const block of log.split("\0").slice(1)) {
    const [seconds, ...files] = block.split("\n").filter(Boolean);
    const day = new Date(Number(seconds) * 1000).toISOString().slice(0, 10);
    for (const file of files) if (tracked.has(file) && !(file in dates)) dates[file] = day;
  }
  for (const [file, entry] of Object.entries(readPullManifest(cwd) ?? {})) {
    if (entry.day) dates[file] = entry.day;
    else delete dates[file];
  }
  return Object.fromEntries(Object.entries(dates).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** The generated module's text. @param {Record<string, string>} dates */
export function sourceDatesModule(dates) {
  return (
    "// Generated by scripts/build-source-dates.mjs from git. Do not edit: build:content (or the next install) writes this\n" +
    "// again. See scripts/lib/source-dates.mjs. Empty in a shallow clone.\n" +
    `export const SOURCE_DATES = Object.freeze(${JSON.stringify(dates, null, 2)});\n`
  );
}

/** Writes the module, and only when it changed. */
export function writeSourceDates() {
  const dates = readSourceDates();
  const text = sourceDatesModule(dates);
  let before = "";
  try {
    before = readFileSync(SOURCE_DATES_PATH, "utf8");
  } catch {
    mkdirSync(path.dirname(SOURCE_DATES_PATH), { recursive: true });
  }
  if (before !== text) writeFileSync(SOURCE_DATES_PATH, text, "utf8");
  return { dates, changed: before !== text };
}
