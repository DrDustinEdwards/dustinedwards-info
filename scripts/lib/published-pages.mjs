// Which prose pages are published, read from their files in content/pages (docs/PAGES.md), and written to
// app/lib/published-pages.generated.mjs for the footer. The footer is on every page and this plane does not
// hydrate, so, like the header's panels (scripts/lib/nav-data.mjs), it reads a fact about the repository's
// content from a build product rather than from the database on every request (the
// repository is the source). A page published through Carrel is a commit to main, and that commit's deploy
// writes this file again. build:content and the install step both call it, so a clone that has not built yet
// still has the module the footer imports.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import matter from "gray-matter";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const PAGES_DIR = path.join(ROOT, "content", "pages");
const PUBLISHED_PAGES_PATH = path.join(ROOT, "app", "lib", "published-pages.generated.mjs");

/**
 * The paths of every page file whose front matter does not say `draft: true`, sorted. The compile
 * (app/lib/pages/compile.mjs) is what judges a file; this reads only the two fields it needs, and a file the
 * compile would refuse is the compile's to report.
 *
 * @param {string} [dir]
 * @returns {string[]}
 */
export function readPublishedPages(dir = PAGES_DIR) {
  /** @type {string[]} */
  const found = [];
  for (const name of readdirSync(dir).filter((n) => n.endsWith(".md"))) {
    const { data } = matter(readFileSync(path.join(dir, name), "utf8"), {});
    if (typeof data.path === "string" && data.draft !== true) found.push(data.path);
  }
  return found.sort();
}

/** The generated module's text. @param {string[]} paths */
function publishedPagesModule(paths) {
  return (
    "// Generated by scripts/build-published-pages.mjs from content/pages. Do not edit: change a page's `draft`,\n" +
    "// and build:content (or the next install) writes this again. See scripts/lib/published-pages.mjs.\n" +
    `export const PUBLISHED_PAGES = Object.freeze(${JSON.stringify(paths, null, 2)});\n`
  );
}

/** Writes the module, and only when it changed. */
export function writePublishedPages() {
  const paths = readPublishedPages();
  const text = publishedPagesModule(paths);
  let before = "";
  try {
    before = readFileSync(PUBLISHED_PAGES_PATH, "utf8");
  } catch {
    mkdirSync(path.dirname(PUBLISHED_PAGES_PATH), { recursive: true });
  }
  if (before !== text) writeFileSync(PUBLISHED_PAGES_PATH, text, "utf8");
  return { paths, changed: before !== text };
}
